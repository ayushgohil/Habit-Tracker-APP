final Map<String, IconData> habitIcons = {
  for (final e in habitIconEntries) e.key: e.icon,
};

IconData habitIconFor(String key) =>
    habitIcons[key] ?? Icons.local_fire_department_rounded;

/// Icons whose key or words contain every word of [query].
List<HabitIconEntry> searchHabitIcons(String query) {
  final words = query.toLowerCase().split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
  if (words.isEmpty) return habitIconEntries;
  return [
    for (final e in habitIconEntries)
      if (words.every((w) => '${e.key} ${e.words}'.toLowerCase().contains(w))) e,
  ];
}
